-- Adopt the deployed schema without rewriting data or advancing sequences.
CREATE SCHEMA IF NOT EXISTS library;
CREATE TABLE IF NOT EXISTS library.loan_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn TEXT UNIQUE,
    media_type TEXT NOT NULL,
    title TEXT NOT NULL,
    author TEXT,
    library TEXT,
    due_date DATE,
    status TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS library.libraries (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS library.import_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference UUID NOT NULL UNIQUE,
    status TEXT NOT NULL,
    front_photo TEXT NOT NULL,
    back_photo TEXT NOT NULL,
    isbn TEXT,
    title TEXT,
    author TEXT,
    media_type TEXT,
    library TEXT,
    loan_item_id BIGINT REFERENCES library.loan_items(id) ON DELETE SET NULL,
    error_detail TEXT,
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_import_jobs_claim ON library.import_jobs(status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_import_jobs_created_at ON library.import_jobs(created_at);
CREATE TABLE IF NOT EXISTS library.ai_pacer (
    id SMALLINT PRIMARY KEY,
    next_call_allowed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
